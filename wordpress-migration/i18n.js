  let current = localStorage.getItem("tpw-language") === "ar" ? "ar" : "fr";

  function interpolate(text, values = {}) {
    return text.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
  }

  function t(key, values = {}) {
    return interpolate(messages[current][key] || messages.fr[key] || key, values);
  }

  function apply() {
    document.documentElement.lang = current;
    document.documentElement.dir = current === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
    });
    const select = document.querySelector("#languageSelect");
    if (select) select.value = current;
  }

  function setLanguage(language) {
    current = language === "ar" ? "ar" : "fr";
    localStorage.setItem("tpw-language", current);
    apply();
    window.dispatchEvent(new CustomEvent("tpw:languagechange", { detail: { language: current } }));
  }

  window.tpwI18n = { t, apply, setLanguage, get language() { return current; } };
  apply();
